// Regenerate the Material 3 color tokens (multiple accents + light/dark):
//   npm i @material/material-color-utilities
//   node tools/gen-theme.mjs > backend/internal/api/public/material-theme.css
// Build-time only — the app ships the generated CSS, not this script or its dep.

import {
  Hct, argbFromHex, hexFromArgb, SchemeTonalSpot, MaterialDynamicColors,
} from '@material/material-color-utilities';

// Accent themes the user can pick. "violet" is the default (also applied when no
// data-accent attribute is set).
const ACCENTS = [
  ['violet', '#4F46E5'],
  ['indigo', '#3730A3'],
  ['teal', '#0D9488'],
  ['green', '#15803D'],
  ['rose', '#E11D48'],
  ['amber', '#D97706'],
];

const roles = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'background', 'onBackground',
  'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'outline', 'outlineVariant', 'shadow', 'scrim',
  'inverseSurface', 'inverseOnSurface', 'inversePrimary',
  'surfaceDim', 'surfaceBright',
  'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest',
];

const kebab = (s) => s.replace(/([A-Z])/g, '-$1').toLowerCase();

function tokens(hex, dark) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(hex)), dark, 0.0);
  return roles.map((r) => {
    const dc = MaterialDynamicColors[r];
    if (!dc || typeof dc.getArgb !== 'function') return null;
    return `  --md-sys-color-${kebab(r)}: ${hexFromArgb(dc.getArgb(scheme))};`;
  }).filter(Boolean).join('\n');
}

// A block that applies `light`/`dark` tokens for a given root selector base.
function block(base, hex) {
  const light = tokens(hex, false);
  const dark = tokens(hex, true);
  return `${base}, ${base}[data-theme="light"] {
${light}
}
@media (prefers-color-scheme: dark) {
  ${base}:not([data-theme="light"]) {
${dark}
  }
}
${base}[data-theme="dark"] {
${dark}
}
`;
}

let out = `/* Material 3 color tokens — generated by tools/gen-theme.mjs. Do not hand-edit.
   Default accent is violet (no data-accent attribute); others via data-accent. */\n\n`;

// Default (no data-accent) = violet.
out += block(':root:not([data-accent])', ACCENTS[0][1]);
out += '\n';
// Named accents.
for (const [name, hex] of ACCENTS) {
  out += block(`:root[data-accent="${name}"]`, hex);
  out += '\n';
}

process.stdout.write(out);
